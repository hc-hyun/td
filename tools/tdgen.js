class TdgenError extends Error {
  constructor(message) {
    super(message);
    this.name = "TdgenError";
  }
}

function rel(filePath) {
  return path.relative(ROOT, filePath).split(path.sep).join("/");
}

function readJson(filePath) {
  try {
    return JSON.parse(fs.readFileSync(filePath, "utf8"));
  } catch (error) {
    if (error.code === "ENOENT") {
      throw new TdgenError(`Missing spec file: ${rel(filePath)}`);
    }
    if (error instanceof SyntaxError) {
      throw new TdgenError(`Invalid JSON in ${rel(filePath)}: ${error.message}`);
    }
    throw error;
  }
}

function writeJson(filePath, value) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, `${JSON.stringify(value, null, 2)}\n`, "utf8");
}

function writeFunction(relPath, lines) {
  const filePath = path.join(FUNCTION, `${relPath}.mcfunction`);
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  const content = [GENERATED, ...lines].join("\n").replace(/\s+$/u, "");
  fs.writeFileSync(filePath, `${content}\n`, "utf8");
}

function writeTag(relPath, values) {
  writeJson(path.join(TAG, `${relPath}.json`), { values });
}

function ns(functionPath) {
  return `td:${functionPath}`;
}

function listJsonFiles(directory) {
  if (!fs.existsSync(directory)) {
    return [];
  }
  return fs
    .readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".json"))
    .map((entry) => path.join(directory, entry.name))
    .sort();
}

function specSortValue(spec) {
  return spec.id ?? spec.number ?? 0;
}

function compareSpecs(left, right) {
  const leftOrder = left.order ?? 1000;
  const rightOrder = right.order ?? 1000;
  if (leftOrder !== rightOrder) {
    return leftOrder < rightOrder ? -1 : 1;
  }
  const leftValue = specSortValue(left);
  const rightValue = specSortValue(right);
  if (typeof leftValue === "number" && typeof rightValue === "number") {
    return leftValue - rightValue;
  }
  return String(leftValue).localeCompare(String(rightValue));
}

function loadSpecs(kind) {
  const specs = [];
  for (const filePath of listJsonFiles(path.join(SPEC, kind))) {
    const value = readJson(filePath);
    if (value.enabled ?? true) {
      value._path = rel(filePath);
      specs.push(value);
    }
  }
  return specs.sort(compareSpecs);
}

function loadGame() {
  const game = readJson(path.join(SPEC, "game.json"));
  return {
    core_hp: game.core_hp ?? 20,
    wave_prep_ticks: game.wave_prep_ticks ?? 600,
    hp_scale: game.hp_scale ?? 10,
    start_money: game.start_money ?? 60,
    combat_refund_divisor: game.combat_refund_divisor ?? 2,
    tower_team: game.tower_team ?? {
      name: "td_tower",
      color: "blue",
      collision_rule: "never",
    },
  };
}

function compactJson(value) {
  return JSON.stringify(value);
}

function snbtString(value) {
  return `'${String(value).replaceAll("\\", "\\\\").replaceAll("'", "\\'")}'`;
}

function scoreboardName(prefix, typeId, suffix) {
  return `$${prefix}_${typeId}_${suffix}`;
}

function formatScale(value) {
  const scale = value ?? 1.0;
  return Number.isInteger(scale) ? `${scale}.0` : String(scale);
}

function generatedFile(filePath) {
  if (!fs.existsSync(filePath) || !fs.statSync(filePath).isFile()) {
    return false;
  }
  const firstLine = fs.readFileSync(filePath, "utf8").split(/\r?\n/u, 1)[0] ?? "";
  return firstLine === GENERATED || firstLine === LEGACY_GENERATED;
}

function cleanGeneratedFiles() {
  const ownedDirs = [
    path.join(FUNCTION, "config", "enemy"),
    path.join(FUNCTION, "config", "tower"),
    path.join(FUNCTION, "enemy", "hpbar", "run"),
    path.join(FUNCTION, "enemy", "hpbar", "type"),
    path.join(FUNCTION, "enemy", "type"),
    path.join(FUNCTION, "shop", "give_item"),
    path.join(FUNCTION, "shop", "use"),
    path.join(FUNCTION, "spawn", "type"),
    path.join(FUNCTION, "tower", "attack", "run"),
    path.join(FUNCTION, "tower", "attack"),
    path.join(FUNCTION, "tower", "place_type"),
    path.join(FUNCTION, "tower", "select"),
    path.join(FUNCTION, "tower", "spawn"),
    path.join(FUNCTION, "tower", "tick"),
    path.join(FUNCTION, "tower", "type"),
    path.join(FUNCTION, "wave", "config"),
  ];
  const ownedFiles = [
    path.join(FUNCTION, "config", "core.mcfunction"),
    path.join(FUNCTION, "config", "economy.mcfunction"),
    path.join(FUNCTION, "team", "load.mcfunction"),
    path.join(FUNCTION, "wave", "run_config.mcfunction"),
  ];

  for (const directory of ownedDirs) {
    if (!fs.existsSync(directory)) {
      continue;
    }
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const filePath = path.join(directory, entry.name);
      if (entry.isFile() && entry.name.endsWith(".mcfunction") && generatedFile(filePath)) {
        fs.unlinkSync(filePath);
      }
    }
  }

  for (const filePath of ownedFiles) {
    if (generatedFile(filePath)) {
      fs.unlinkSync(filePath);
    }
  }
}

function validateTypeId(typeId, kind) {
  if (!TYPE_RE.test(typeId)) {
    throw new TdgenError(`Invalid ${kind} id '${typeId}'. Use lowercase letters, numbers, and underscores.`);
  }
}

function requireFields(spec, fields, label) {
  const missing = fields.filter((field) => !(field in spec));
  if (missing.length > 0) {
    throw new TdgenError(`${label} is missing required field(s): ${missing.join(", ")}`);
  }
}

