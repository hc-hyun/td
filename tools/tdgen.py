def render_enemy_hpbar_type(enemy: dict[str, Any]) -> list[str]:
    name = enemy["display_name"]
    bold = ",bold:true" if enemy.get("hpbar_bold", enemy.get("bold", False)) else ""
    lines: list[str] = []
    for ratio in range(10, 0, -1):
        full = "█" * ratio
        empty = "░" * (10 - ratio)
        text = f"{name} {ratio}/10 {full}{empty}"
        color = HP_COLORS[ratio]
        lines.append(
            f"execute if score @s td.hp_ratio matches {ratio} run data merge entity @s "
            f"{{CustomNameVisible:1b,CustomName:{{text:{snbt_string(text)},color:{snbt_string(color)}{bold}}}}}"
        )
    return lines


