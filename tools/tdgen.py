class TdgenError(Exception):
    pass


def read_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise TdgenError(f"Missing spec file: {path}") from exc
    except json.JSONDecodeError as exc:
        raise TdgenError(f"Invalid JSON in {path}: {exc}") from exc


def write_json(path: Path, value: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def write_function(rel_path: str, lines: list[str]) -> None:
    path = FUNCTION / f"{rel_path}.mcfunction"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join([GENERATED, *lines]).rstrip() + "\n", encoding="utf-8")


def write_tag(rel_path: str, values: list[str]) -> None:
    write_json(TAG / f"{rel_path}.json", {"values": values})


def ns(path: str) -> str:
    return f"td:{path}"


def load_specs(kind: str) -> list[dict[str, Any]]:
    specs: list[dict[str, Any]] = []
    for path in sorted((SPEC / kind).glob("*.json")):
        value = read_json(path)
        if value.get("enabled", True):
            value["_path"] = str(path.relative_to(ROOT))
            specs.append(value)
    return sorted(specs, key=lambda item: (item.get("order", 1000), item.get("id", item.get("number", 0))))


def load_game() -> dict[str, Any]:
    game = read_json(SPEC / "game.json")
    return {
        "core_hp": game.get("core_hp", 20),
        "wave_prep_ticks": game.get("wave_prep_ticks", 600),
        "hp_scale": game.get("hp_scale", 10),
        "start_money": game.get("start_money", 60),
        "combat_refund_divisor": game.get("combat_refund_divisor", 2),
        "tower_team": game.get("tower_team", {"name": "td_tower", "color": "blue", "collision_rule": "never"}),
    }


def compact_json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def snbt_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def scoreboard_name(prefix: str, type_id: str, suffix: str) -> str:
    return f"${prefix}_{type_id}_{suffix}"


def generated_file(path: Path) -> bool:
    if not path.exists() or not path.is_file():
        return False
    try:
        return path.read_text(encoding="utf-8").splitlines()[0] == GENERATED
    except IndexError:
        return False


def clean_generated_files() -> None:
    owned_dirs = [
        FUNCTION / "config" / "enemy",
        FUNCTION / "config" / "tower",
        FUNCTION / "enemy" / "hpbar" / "run",
        FUNCTION / "enemy" / "hpbar" / "type",
        FUNCTION / "enemy" / "type",
        FUNCTION / "shop" / "give_item",
        FUNCTION / "shop" / "use",
        FUNCTION / "spawn" / "type",
        FUNCTION / "tower" / "attack" / "run",
        FUNCTION / "tower" / "attack",
        FUNCTION / "tower" / "place_type",
        FUNCTION / "tower" / "select",
        FUNCTION / "tower" / "spawn",
        FUNCTION / "tower" / "tick",
        FUNCTION / "tower" / "type",
        FUNCTION / "wave" / "config",
    ]
    owned_files = [
        FUNCTION / "config" / "core.mcfunction",
        FUNCTION / "config" / "economy.mcfunction",
        FUNCTION / "team" / "load.mcfunction",
        FUNCTION / "wave" / "run_config.mcfunction",
    ]
    for directory in owned_dirs:
        if not directory.exists():
            continue
        for path in directory.glob("*.mcfunction"):
            if generated_file(path):
                path.unlink()
    for path in owned_files:
        if generated_file(path):
            path.unlink()


def validate_type_id(type_id: str, kind: str) -> None:
    if not TYPE_RE.match(type_id):
        raise TdgenError(f"Invalid {kind} id '{type_id}'. Use lowercase letters, numbers, and underscores.")


def require_fields(spec: dict[str, Any], fields: list[str], label: str) -> None:
    missing = [field for field in fields if field not in spec]
    if missing:
        raise TdgenError(f"{label} is missing required field(s): {', '.join(missing)}")


def equipment_lines(equipment: list[dict[str, str]]) -> list[str]:
    lines = []
    for item in equipment:
        lines.append(f"item replace entity @s {item['slot']} with {item['item']}")
    return lines


