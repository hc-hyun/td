function renderWaveConfig(wave) {
  const title = wave.title ?? `Wave ${formatWave(wave.number)}`;
  const lines = [`# Wave ${formatWave(wave.number)}: ${title}.`];
  const events = [...(wave.events ?? [])].sort((left, right) => left.tick - right.tick);
  for (const event of events) {
    const tick = event.tick;
    const mode = event.mode ?? "random";
    const typeId = event.type;
    let call;
    if (mode === "random") {
      call = `function td:spawn/random {type:"${typeId}"}`;
    } else if (mode === "from") {
      call = `function td:spawn/from {type:"${typeId}",id:${event.id}}`;
    } else if (mode === "all") {
      call = `function td:spawn/all {type:"${typeId}"}`;
    } else {
      throw new TdgenError(`Unknown wave spawn mode in wave ${wave.number}: ${mode}`);
    }
    lines.push(`execute if score $wave_time td.wave_time matches ${tick} run ${call}`);
  }
  lines.push(`execute if score $wave_time td.wave_time matches ${wave.complete_tick} run scoreboard players set $wave_done td.wave_done 1`);
  return lines;
}

function renderWaveRunConfig(waves) {
  const lines = ["# 현재 $wave 번호에 맞는 생성된 웨이브 스폰표를 실행합니다."];
  for (const wave of waves) {
    lines.push(`execute if score $wave td.wave matches ${wave.number} run function td:wave/config/wave_${formatWave(wave.number)}`);
  }
  return lines;
}

function build() {
  validateSpecs();
  const game = loadGame();
  const enemies = loadSpecs("enemies");
  const towers = loadSpecs("towers");
  const waves = loadSpecs("waves").sort((left, right) => left.number - right.number);
  const lastWave = waves.length > 0 ? Math.max(...waves.map((wave) => wave.number)) : 0;

  cleanGeneratedFiles();

  writeFunction("config/core", renderConfigCore(game, lastWave));
  writeFunction("config/economy", renderConfigEconomy(game, towers));
  writeFunction("team/load", renderTeamLoad(game, enemies));

  for (const enemy of enemies) {
    const typeId = enemy.id;
    writeFunction(`config/enemy/${typeId}`, renderEnemyConfig(enemy));
    writeFunction(`spawn/type/${typeId}`, renderEnemySpawn(enemy));
    writeFunction(`enemy/type/${typeId}`, renderEnemyType(enemy));
    writeFunction(`enemy/hpbar/type/${typeId}`, renderEnemyHpbarType(enemy));
    writeFunction(`enemy/hpbar/run/${typeId}`, renderEnemyHpbarRun(enemy));
  }

  for (const tower of towers) {
    const typeId = tower.id;
    writeFunction(`config/tower/${typeId}`, renderTowerConfig(tower));
    writeFunction(`shop/give_item/${typeId}`, renderShopGiveItem(tower));
    writeFunction(`shop/use/${typeId}`, renderShopUse(tower));
    writeFunction(`tower/select/${typeId}`, renderTowerSelect(tower));
    writeFunction(`tower/place_type/${typeId}`, renderTowerPlaceType(tower));
    writeFunction(`tower/spawn/${typeId}`, renderTowerSpawn(tower));
    writeFunction(`tower/type/${typeId}`, renderTowerType(tower));
    writeFunction(`tower/tick/${typeId}`, renderTowerTick(tower));
    writeFunction(`tower/attack/${typeId}`, renderTowerAttack(tower));
    writeFunction(`tower/attack/run/${typeId}`, renderTowerAttackRun(tower));
  }

  writeFunction("tower/select/clear", renderTowerSelectClear(towers));

  for (const wave of waves) {
    writeFunction(`wave/config/wave_${formatWave(wave.number)}`, renderWaveConfig(wave));
  }
  writeFunction("wave/run_config", renderWaveRunConfig(waves));

  writeTag("config/load", [
    ns("config/core"),
    ns("config/economy"),
    ...enemies.map((enemy) => ns(`config/enemy/${enemy.id}`)),
    ...towers.map((tower) => ns(`config/tower/${tower.id}`)),
  ]);
  writeTag("enemy/hpbar_types", enemies.map((enemy) => ns(`enemy/hpbar/run/${enemy.id}`)));
  writeTag("shop/give_items", [...towers.map((tower) => ns(`shop/give_item/${tower.id}`)), ns("shop/give_item/remove_tower")]);
  writeTag("shop/use_items", [...towers.map((tower) => ns(`shop/use/${tower.id}`)), ns("shop/use/remove_tower")]);
  writeTag("tower/place_types", towers.map((tower) => ns(`tower/place_type/${tower.id}`)));
  writeTag("tower/tick_types", towers.map((tower) => ns(`tower/tick/${tower.id}`)));
}

function validateSpecs() {
  const game = loadGame();
  if (Number(game.combat_refund_divisor) <= 0) {
    throw new TdgenError("combat_refund_divisor must be greater than 0.");
  }

  const enemies = loadSpecs("enemies");
  const towers = loadSpecs("towers");
  const waves = loadSpecs("waves");
  const enemyIds = new Set(enemies.map((enemy) => enemy.id));
  const towerIds = new Set(towers.map((tower) => tower.id));

  checkArchiveCollisions("enemies", enemyIds);
  checkArchiveCollisions("towers", towerIds);
  checkArchiveCollisions("waves", new Set(waves.map((wave) => `wave_${formatWave(wave.number)}`)));

  for (const enemy of enemies) {
    requireFields(enemy, ["id", "display_name", "entity", "hp", "speed", "reward", "core_damage", "team"], enemy._path ?? "enemy");
    validateTypeId(enemy.id, "enemy");
    if (enemy.team?.name == null) {
      throw new TdgenError(`Enemy ${enemy.id} needs team.name`);
    }
  }

  for (const tower of towers) {
    requireFields(tower, ["id", "display_name", "cost", "damage", "initial_cooldown", "range", "cooldown", "shop", "attack"], tower._path ?? "tower");
    validateTypeId(tower.id, "tower");
    const preset = tower.attack.preset ?? "single";
    if (!new Set(["single", "splash", "blink", "raw"]).has(preset)) {
      throw new TdgenError(`Tower ${tower.id} has unsupported attack preset: ${preset}`);
    }
  }

  const seenWaves = new Set();
  for (const wave of waves) {
    requireFields(wave, ["number", "complete_tick", "events"], wave._path ?? "wave");
    const number = Number(wave.number);
    if (seenWaves.has(number)) {
      throw new TdgenError(`Duplicate wave number: ${number}`);
    }
    seenWaves.add(number);
    for (const event of wave.events ?? []) {
      requireFields(event, ["tick", "type"], `wave ${number} event`);
      if (!enemyIds.has(event.type)) {
        throw new TdgenError(`Wave ${number} references missing enemy type: ${event.type}`);
      }
      const mode = event.mode ?? "random";
      if (!new Set(["random", "from", "all"]).has(mode)) {
        throw new TdgenError(`Wave ${number} has unsupported spawn mode: ${mode}`);
      }
      if (mode === "from" && !("id" in event)) {
        throw new TdgenError(`Wave ${number} from-spawn event needs id`);
      }
    }
  }
}

function checkArchiveCollisions(kind, activeIds) {
  const archiveDir = path.join(ARCHIVE, kind);
  if (!fs.existsSync(archiveDir)) {
    return;
  }
  for (const filePath of listJsonFiles(archiveDir)) {
    const itemId = path.basename(filePath, ".json");
    if (activeIds.has(itemId)) {
      throw new TdgenError(`${kind} spec exists in both active and archive: ${itemId}`);
    }
  }
}

function listSpecs(kind) {
  const kinds = kind === "all" ? ["enemies", "towers", "waves"] : [pluralKind(kind)];
  for (const current of kinds) {
    console.log(`[${current}]`);
    for (const spec of loadSpecs(current)) {
      const label = current === "waves" ? `wave_${formatWave(spec.number)}` : spec.id;
      console.log(`  active   ${label}`);
    }
    const archiveDir = path.join(ARCHIVE, current);
    if (fs.existsSync(archiveDir)) {
      for (const filePath of listJsonFiles(archiveDir)) {
        console.log(`  archived ${path.basename(filePath, ".json")}`);
      }
    }
  }
}

function pluralKind(kind) {
  const mapping = {
    enemy: "enemies",
    tower: "towers",
    wave: "waves",
    enemies: "enemies",
    towers: "towers",
    waves: "waves",
  };
  if (!(kind in mapping)) {
    throw new TdgenError(`Unsupported kind: ${kind}`);
  }
  return mapping[kind];
}

function activeSpecPath(kind, itemId) {
  const plural = pluralKind(kind);
  if (plural === "waves") {
    return path.join(SPEC, plural, `wave_${formatWave(parseWaveNumber(itemId))}.json`);
  }
  return path.join(SPEC, plural, `${itemId}.json`);
}

function archiveSpecPath(kind, itemId) {
  const plural = pluralKind(kind);
  if (plural === "waves") {
    return path.join(ARCHIVE, plural, `wave_${formatWave(parseWaveNumber(itemId))}.json`);
  }
  return path.join(ARCHIVE, plural, `${itemId}.json`);
}

function parseWaveNumber(value) {
  const text = String(value).startsWith("wave_") ? String(value).slice("wave_".length) : String(value);
  if (!/^\d+$/u.test(text)) {
    throw new TdgenError(`Invalid wave id: ${value}`);
  }
  return Number.parseInt(text, 10);
}

function formatWave(number) {
  return String(Number(number)).padStart(2, "0");
}

function addSpec(kind, itemId, source) {
  const src = activeSpecPath(kind, source);
  const dst = activeSpecPath(kind, itemId);
  if (fs.existsSync(dst)) {
    throw new TdgenError(`Spec already exists: ${rel(dst)}`);
  }
  if (!fs.existsSync(src)) {
    throw new TdgenError(`Source spec not found: ${rel(src)}`);
  }
  const spec = readJson(src);
  if (pluralKind(kind) === "waves") {
    const number = parseWaveNumber(itemId);
    spec.number = number;
    spec.title = `Copied wave ${formatWave(number)}`;
    spec.order = number;
  } else {
    validateTypeId(itemId, kind);
    spec.id = itemId;
    spec.display_name = titleName(itemId);
    if (pluralKind(kind) === "enemies") {
      spec.team.name = `td_enemy_${itemId}`;
    }
    if (pluralKind(kind) === "towers") {
      spec.shop.item_name = `${titleName(itemId)} Tower`;
    }
  }
  writeJson(dst, spec);
  build();
}

function titleName(typeId) {
  return String(typeId)
    .split("_")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

function deleteSpec(kind, itemId) {
  const src = activeSpecPath(kind, itemId);
  const dst = archiveSpecPath(kind, itemId);
  if (!fs.existsSync(src)) {
    throw new TdgenError(`Active spec not found: ${rel(src)}`);
  }
  if (fs.existsSync(dst)) {
    throw new TdgenError(`Archive spec already exists: ${rel(dst)}`);
  }
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.renameSync(src, dst);
  build();
}

function restoreSpec(kind, itemId) {
  const src = archiveSpecPath(kind, itemId);
  const dst = activeSpecPath(kind, itemId);
  if (!fs.existsSync(src)) {
    throw new TdgenError(`Archived spec not found: ${rel(src)}`);
  }
  if (fs.existsSync(dst)) {
    throw new TdgenError(`Active spec already exists: ${rel(dst)}`);
  }
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.renameSync(src, dst);
  build();
}

function rootHelp() {
  return `usage: tdgen.js [-h] {build,validate,list,add,delete,restore} ...

Generate BlackWoolTD datapack files from JSON specs.

positional arguments:
  {build,validate,list,add,delete,restore}

options:
  -h, --help            show this help message and exit`;
}

function subcommandHelp(command) {
  if (command === "list") {
    return `usage: tdgen.js list [-h] {all,enemy,tower,wave}

positional arguments:
  {all,enemy,tower,wave}

options:
  -h, --help            show this help message and exit`;
  }
  if (command === "add") {
    return `usage: tdgen.js add [-h] --from SOURCE {enemy,tower,wave} id

positional arguments:
  {enemy,tower,wave}
  id

options:
  -h, --help          show this help message and exit
  --from SOURCE`;
  }
  if (command === "delete" || command === "restore") {
    return `usage: tdgen.js ${command} [-h] {enemy,tower,wave} id

positional arguments:
  {enemy,tower,wave}
  id

options:
  -h, --help          show this help message and exit`;
  }
  return rootHelp();
}

function hasHelp(args) {
  return args.includes("-h") || args.includes("--help");
}

function requireChoice(value, choices, label) {
  if (!choices.includes(value)) {
    throw new TdgenError(`Invalid ${label}: ${value}`);
  }
}

function parseAddArgs(args) {
  const positional = [];
  let source = null;
  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === "--from") {
      source = args[index + 1];
      index += 1;
    } else if (arg.startsWith("--from=")) {
      source = arg.slice("--from=".length);
    } else {
      positional.push(arg);
    }
  }
  if (positional.length !== 2 || !source) {
    throw new TdgenError("Usage: tdgen.js add {enemy,tower,wave} id --from SOURCE");
  }
  return { kind: positional[0], id: positional[1], source };
}

function main(argv = process.argv.slice(2)) {
  if (argv.length === 0 || hasHelp(argv)) {
    const command = argv.find((arg) => !arg.startsWith("-"));
    console.log(command ? subcommandHelp(command) : rootHelp());
    return 0;
  }

  try {
    const [command, ...args] = argv;
    if (command === "build") {
      build();
    } else if (command === "validate") {
      validateSpecs();
    } else if (command === "list") {
      if (args.length !== 1) {
        throw new TdgenError("Usage: tdgen.js list {all,enemy,tower,wave}");
      }
      requireChoice(args[0], ["all", "enemy", "tower", "wave"], "list kind");
      listSpecs(args[0]);
    } else if (command === "add") {
      const { kind, id, source } = parseAddArgs(args);
      requireChoice(kind, ["enemy", "tower", "wave"], "add kind");
      addSpec(kind, id, source);
    } else if (command === "delete") {
      if (args.length !== 2) {
        throw new TdgenError("Usage: tdgen.js delete {enemy,tower,wave} id");
      }
      requireChoice(args[0], ["enemy", "tower", "wave"], "delete kind");
      deleteSpec(args[0], args[1]);
    } else if (command === "restore") {
      if (args.length !== 2) {
        throw new TdgenError("Usage: tdgen.js restore {enemy,tower,wave} id");
      }
      requireChoice(args[0], ["enemy", "tower", "wave"], "restore kind");
      restoreSpec(args[0], args[1]);
    } else {
      throw new TdgenError(`Unknown command: ${command}`);
    }
    return 0;
  } catch (error) {
    if (error instanceof TdgenError) {
      console.error(`tdgen: ${error.message}`);
      return 1;
    }
    throw error;
  }
}

