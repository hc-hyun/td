def render_tower_attack(tower: dict[str, Any]) -> list[str]:
    type_id = tower["id"]
    attack = tower["attack"]
    preset = attack.get("preset", "single")
    if preset == "raw":
        return attack.get("lines", [])
    if preset == "single":
        return render_tower_attack_single(tower)
    if preset == "splash":
        return render_tower_attack_splash(tower)
    if preset == "blink":
        return render_tower_attack_blink(tower)
    raise TdgenError(f"Unknown tower attack preset for {type_id}: {preset}")


