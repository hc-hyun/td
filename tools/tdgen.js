function renderTowerAttack(tower) {
  const preset = tower.attack.preset ?? "single";
  if (preset === "raw") {
    return tower.attack.lines ?? [];
  }
  if (preset === "single") {
    return renderTowerAttackSingle(tower);
  }
  if (preset === "splash") {
    return renderTowerAttackSplash(tower);
  }
  if (preset === "blink") {
    return renderTowerAttackBlink(tower);
  }
  throw new TdgenError(`Unknown tower attack preset for ${tower.id}: ${preset}`);
}

