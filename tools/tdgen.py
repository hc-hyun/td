def render_wave_config(wave: dict[str, Any]) -> list[str]:
    title = wave.get("title", f"Wave {wave['number']:02d}")
    lines = [f"# Wave {wave['number']:02d}: {title}."]
    for event in sorted(wave.get("events", []), key=lambda item: item["tick"]):
        tick = event["tick"]
        mode = event.get("mode", "random")
        type_id = event["type"]
        if mode == "random":
            call = f'function td:spawn/random {{type:"{type_id}"}}'
        elif mode == "from":
            call = f'function td:spawn/from {{type:"{type_id}",id:{event["id"]}}}'
        elif mode == "all":
            call = f'function td:spawn/all {{type:"{type_id}"}}'
        else:
            raise TdgenError(f"Unknown wave spawn mode in wave {wave['number']}: {mode}")
        lines.append(f"execute if score $wave_time td.wave_time matches {tick} run {call}")
    lines.append(
        f"execute if score $wave_time td.wave_time matches {wave['complete_tick']} run scoreboard players set $wave_done td.wave_done 1"
    )
    return lines


def render_wave_run_config(waves: list[dict[str, Any]]) -> list[str]:
    lines = ["# 현재 $wave 번호에 맞는 생성된 웨이브 스폰표를 실행합니다."]
    for wave in waves:
        number = wave["number"]
        lines.append(f"execute if score $wave td.wave matches {number} run function td:wave/config/wave_{number:02d}")
    return lines


def build() -> None:
    validate_specs()
    game = load_game()
    enemies = load_specs("enemies")
    towers = load_specs("towers")
    waves = sorted(load_specs("waves"), key=lambda item: item["number"])
    last_wave = max((wave["number"] for wave in waves), default=0)

    clean_generated_files()

    write_function("config/core", render_config_core(game, last_wave))
    write_function("config/economy", render_config_economy(game, towers))
    write_function("team/load", render_team_load(game, enemies))

    for enemy in enemies:
        type_id = enemy["id"]
        write_function(f"config/enemy/{type_id}", render_enemy_config(enemy))
        write_function(f"spawn/type/{type_id}", render_enemy_spawn(enemy))
        write_function(f"enemy/type/{type_id}", render_enemy_type(enemy))
        write_function(f"enemy/hpbar/type/{type_id}", render_enemy_hpbar_type(enemy))
        write_function(f"enemy/hpbar/run/{type_id}", render_enemy_hpbar_run(enemy))

    for tower in towers:
        type_id = tower["id"]
        write_function(f"config/tower/{type_id}", render_tower_config(tower))
        write_function(f"shop/give_item/{type_id}", render_shop_give_item(tower))
        write_function(f"shop/use/{type_id}", render_shop_use(tower))
        write_function(f"tower/select/{type_id}", render_tower_select(tower))
        write_function(f"tower/place_type/{type_id}", render_tower_place_type(tower))
        write_function(f"tower/spawn/{type_id}", render_tower_spawn(tower))
        write_function(f"tower/type/{type_id}", render_tower_type(tower))
        write_function(f"tower/tick/{type_id}", render_tower_tick(tower))
        write_function(f"tower/attack/{type_id}", render_tower_attack(tower))
        write_function(f"tower/attack/run/{type_id}", render_tower_attack_run(tower))

    write_function("tower/select/clear", render_tower_select_clear(towers))

    for wave in waves:
        write_function(f"wave/config/wave_{wave['number']:02d}", render_wave_config(wave))
    write_function("wave/run_config", render_wave_run_config(waves))

    write_tag("config/load", [ns("config/core"), ns("config/economy"), *[ns(f"config/enemy/{e['id']}") for e in enemies], *[ns(f"config/tower/{t['id']}") for t in towers]])
    write_tag("enemy/hpbar_types", [ns(f"enemy/hpbar/run/{enemy['id']}") for enemy in enemies])
    write_tag("shop/give_items", [*[ns(f"shop/give_item/{tower['id']}") for tower in towers], ns("shop/give_item/remove_tower")])
    write_tag("shop/use_items", [*[ns(f"shop/use/{tower['id']}") for tower in towers], ns("shop/use/remove_tower")])
    write_tag("tower/place_types", [ns(f"tower/place_type/{tower['id']}") for tower in towers])
    write_tag("tower/tick_types", [ns(f"tower/tick/{tower['id']}") for tower in towers])


def validate_specs() -> None:
    game = load_game()
    if int(game["combat_refund_divisor"]) <= 0:
        raise TdgenError("combat_refund_divisor must be greater than 0.")

    enemies = load_specs("enemies")
    towers = load_specs("towers")
    waves = load_specs("waves")
    enemy_ids = {enemy["id"] for enemy in enemies}
    tower_ids = {tower["id"] for tower in towers}

    check_archive_collisions("enemies", enemy_ids)
    check_archive_collisions("towers", tower_ids)
    check_archive_collisions("waves", {f"wave_{wave['number']:02d}" for wave in waves})

    for enemy in enemies:
        require_fields(enemy, ["id", "display_name", "entity", "hp", "speed", "reward", "core_damage", "team"], enemy.get("_path", "enemy"))
        validate_type_id(enemy["id"], "enemy")
        if enemy["team"].get("name") is None:
            raise TdgenError(f"Enemy {enemy['id']} needs team.name")

    for tower in towers:
        require_fields(tower, ["id", "display_name", "cost", "damage", "initial_cooldown", "range", "cooldown", "shop", "attack"], tower.get("_path", "tower"))
        validate_type_id(tower["id"], "tower")
        preset = tower["attack"].get("preset", "single")
        if preset not in {"single", "splash", "blink", "raw"}:
            raise TdgenError(f"Tower {tower['id']} has unsupported attack preset: {preset}")

    seen_waves: set[int] = set()
    for wave in waves:
        require_fields(wave, ["number", "complete_tick", "events"], wave.get("_path", "wave"))
        number = int(wave["number"])
        if number in seen_waves:
            raise TdgenError(f"Duplicate wave number: {number}")
        seen_waves.add(number)
        for event in wave.get("events", []):
            require_fields(event, ["tick", "type"], f"wave {number} event")
            if event["type"] not in enemy_ids:
                raise TdgenError(f"Wave {number} references missing enemy type: {event['type']}")
            mode = event.get("mode", "random")
            if mode not in {"random", "from", "all"}:
                raise TdgenError(f"Wave {number} has unsupported spawn mode: {mode}")
            if mode == "from" and "id" not in event:
                raise TdgenError(f"Wave {number} from-spawn event needs id")


def check_archive_collisions(kind: str, active_ids: set[str]) -> None:
    archive_dir = ARCHIVE / kind
    if not archive_dir.exists():
        return
    for path in archive_dir.glob("*.json"):
        item_id = path.stem
        if kind == "waves":
            item_id = path.stem
        if item_id in active_ids:
            raise TdgenError(f"{kind} spec exists in both active and archive: {item_id}")


def list_specs(kind: str) -> None:
    kinds = ["enemies", "towers", "waves"] if kind == "all" else [plural_kind(kind)]
    for current in kinds:
        print(f"[{current}]")
        for spec in load_specs(current):
            label = f"wave_{spec['number']:02d}" if current == "waves" else spec["id"]
            print(f"  active   {label}")
        archive_dir = ARCHIVE / current
        if archive_dir.exists():
            for path in sorted(archive_dir.glob("*.json")):
                print(f"  archived {path.stem}")


def plural_kind(kind: str) -> str:
    mapping = {"enemy": "enemies", "tower": "towers", "wave": "waves", "enemies": "enemies", "towers": "towers", "waves": "waves"}
    if kind not in mapping:
        raise TdgenError(f"Unsupported kind: {kind}")
    return mapping[kind]


def active_spec_path(kind: str, item_id: str) -> Path:
    plural = plural_kind(kind)
    if plural == "waves":
        number = parse_wave_number(item_id)
        return SPEC / plural / f"wave_{number:02d}.json"
    return SPEC / plural / f"{item_id}.json"


def archive_spec_path(kind: str, item_id: str) -> Path:
    plural = plural_kind(kind)
    if plural == "waves":
        number = parse_wave_number(item_id)
        return ARCHIVE / plural / f"wave_{number:02d}.json"
    return ARCHIVE / plural / f"{item_id}.json"


def parse_wave_number(value: str) -> int:
    text = value.removeprefix("wave_")
    try:
        return int(text)
    except ValueError as exc:
        raise TdgenError(f"Invalid wave id: {value}") from exc


def add_spec(kind: str, item_id: str, source: str) -> None:
    src = active_spec_path(kind, source)
    dst = active_spec_path(kind, item_id)
    if dst.exists():
        raise TdgenError(f"Spec already exists: {dst}")
    if not src.exists():
        raise TdgenError(f"Source spec not found: {src}")
    spec = read_json(src)
    if plural_kind(kind) == "waves":
        number = parse_wave_number(item_id)
        spec["number"] = number
        spec["title"] = f"Copied wave {number:02d}"
        spec["order"] = number
    else:
        validate_type_id(item_id, kind)
        spec["id"] = item_id
        spec["display_name"] = title_name(item_id)
        if plural_kind(kind) == "enemies":
            spec["team"]["name"] = f"td_enemy_{item_id}"
        if plural_kind(kind) == "towers":
            spec["shop"]["item_name"] = f"{title_name(item_id)} Tower"
    write_json(dst, spec)
    build()


def title_name(type_id: str) -> str:
    return " ".join(part.capitalize() for part in type_id.split("_"))


def delete_spec(kind: str, item_id: str) -> None:
    src = active_spec_path(kind, item_id)
    dst = archive_spec_path(kind, item_id)
    if not src.exists():
        raise TdgenError(f"Active spec not found: {src}")
    if dst.exists():
        raise TdgenError(f"Archive spec already exists: {dst}")
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.move(str(src), str(dst))
    build()


def restore_spec(kind: str, item_id: str) -> None:
    src = archive_spec_path(kind, item_id)
    dst = active_spec_path(kind, item_id)
    if not src.exists():
        raise TdgenError(f"Archived spec not found: {src}")
    if dst.exists():
        raise TdgenError(f"Active spec already exists: {dst}")
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.move(str(src), str(dst))
    build()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate BlackWoolTD datapack files from JSON specs.")
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("build")
    sub.add_parser("validate")
    list_parser = sub.add_parser("list")
    list_parser.add_argument("kind", choices=["all", "enemy", "tower", "wave"])

    add_parser = sub.add_parser("add")
    add_parser.add_argument("kind", choices=["enemy", "tower", "wave"])
    add_parser.add_argument("id")
    add_parser.add_argument("--from", dest="source", required=True)

    delete_parser = sub.add_parser("delete")
    delete_parser.add_argument("kind", choices=["enemy", "tower", "wave"])
    delete_parser.add_argument("id")

    restore_parser = sub.add_parser("restore")
    restore_parser.add_argument("kind", choices=["enemy", "tower", "wave"])
    restore_parser.add_argument("id")

    args = parser.parse_args(argv)
    try:
        if args.command == "build":
            build()
        elif args.command == "validate":
            validate_specs()
        elif args.command == "list":
            list_specs(args.kind)
        elif args.command == "add":
            add_spec(args.kind, args.id, args.source)
        elif args.command == "delete":
            delete_spec(args.kind, args.id)
        elif args.command == "restore":
            restore_spec(args.kind, args.id)
        return 0
    except TdgenError as exc:
        print(f"tdgen: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
